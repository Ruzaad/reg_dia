# Genera esquema.sql (orden: extensiones, tablas sin defaults de funciones, funciones, defaults, constraints, índices, vistas, triggers, secuencias)
import json,re,sys,os
sys.path.insert(0,os.path.dirname(__file__))
from extraer import fila
e=fila('raw/esquema.txt','j'); F=fila('raw/funciones.txt','f')
out=[]
w=out.append
w("create schema if not exists extensions;")
w("create extension if not exists pgcrypto schema extensions;")
w("create extension if not exists \"uuid-ossp\" schema extensions;")
w("do $$begin create role anon; exception when others then null; end$$;")
w("do $$begin create role authenticated; exception when others then null; end$$;")
w("do $$begin create role service_role; exception when others then null; end$$;")
w("set check_function_bodies = off;")
w("set search_path = public, extensions;")
for s in e['seqs']:
    w(f"create sequence if not exists public.{s['s']};")
later=[]
for t in e['tablas']:
    cols=[]
    for c in t['cols']:
        x=f'"{c["n"]}" {c["ty"]}'
        if c['id']: x+=" generated always as identity" if c['id']=='a' else " generated by default as identity"
        if c['gen']: x+=f" generated always as {c['def']} stored"
        elif c['def']:
            if re.search(r'\b_\w+\(',c['def']): later.append(f'alter table public.{t["t"]} alter column "{c["n"]}" set default {c["def"]};')
            else: x+=f" default {c['def']}"
        if c['nn']: x+=" not null"
        cols.append(x)
    w(f"create table public.{t['t']} (\n  "+",\n  ".join(cols)+"\n);")
for f in F: w(f['d'].rstrip()+";")
out+=later
pre=len(out)
order={'p':0,'u':1,'c':2,'f':3}
for c in sorted(e['cons'],key=lambda c:order[c['ty']]):
    w(f'alter table public.{c["t"]} add constraint "{c["n"]}" {c["d"]}'+(' not valid' if c['ty'] in 'fc' else '')+';')
for i in e['idx']: w(i+";")
for v in e['views']: w(f"create view public.{v['v']} as {v['d'].rstrip().rstrip(';')};")
for t in e['trig']: w(t+";")
open('build/esquema.sql','w').write("\n".join(out)+"\n")
json.dump({"pre":out[:pre],"post":out[pre:],"seqs":e["seqs"]},open("build/esquema_stmts.json","w"))
print(len(out))
